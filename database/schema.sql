-- Run this in Supabase SQL Editor.
-- Orders are inserted by the Express backend using its server-side service-role key.
create extension if not exists pgcrypto;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null check (char_length(customer_name) >= 2),
  customer_phone text not null,
  delivery_address text not null,
  delivery_notes text default '',
  subtotal integer not null check (subtotal >= 0),
  delivery_fee integer not null check (delivery_fee >= 0),
  total integer not null check (total = subtotal + delivery_fee),
  status text not null default 'received' check (status in ('received','preparing','ready','delivered','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  food_id text not null,
  food_name text not null,
  unit_price integer not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total integer not null check (line_total = unit_price * quantity)
);

-- Enable RLS. The public browser client receives no direct access to orders.
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- No anonymous policies are intentionally created. Server-side service role is used only in backend/.env.
